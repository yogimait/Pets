#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
struct PolicyFile {
    path: String,
    exists: bool,
    content: String,
    hash: String,
    bytes: usize,
    error: Option<String>,
}

#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
struct PolicyBundle {
    global: PolicyFile,
    project: Option<PolicyFile>,
    loaded_at: u64,
}

fn fnv1a(value: &str) -> String {
    let mut hash: u64 = 0xcbf29ce484222325;
    for byte in value.as_bytes() {
        hash ^= *byte as u64;
        hash = hash.wrapping_mul(0x100000001b3);
    }
    format!("{hash:016x}")
}

pub(crate) fn now_ms() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|duration| duration.as_millis() as u64)
        .unwrap_or(0)
}

pub(crate) fn global_policy_path() -> PathBuf {
    if let Ok(path) = std::env::var("AGENT_BOTS_GLOBAL_POLICY") {
        return PathBuf::from(path);
    }
    let home = std::env::var("USERPROFILE")
        .or_else(|_| std::env::var("HOME"))
        .unwrap_or_default();
    PathBuf::from(home)
        .join(".config")
        .join("opencode")
        .join("AGENTS.md")
}

pub(crate) fn devvault_path() -> PathBuf {
    if let Ok(path) = std::env::var("DEVVAULT_PATH") {
        return PathBuf::from(path);
    }
    let home = std::env::var("USERPROFILE")
        .or_else(|_| std::env::var("HOME"))
        .unwrap_or_default();
    PathBuf::from(home).join("Obsidian").join("DevVault")
}

fn install_bundled_agents() -> Result<(), String> {
    let directory = global_policy_path()
        .parent()
        .map(|path| path.join("agent"))
        .ok_or_else(|| "Could not resolve the OpenCode agent directory.".to_string())?;
    fs::create_dir_all(&directory)
        .map_err(|error| format!("Could not create {}: {error}", directory.display()))?;
    let vault = devvault_path().display().to_string().replace('\\', "\\\\");
    let agents = [
        ("orchestrator-workforce", include_str!("../../.opencode/agents/orchestrator-workforce.md")),
        ("dreamer", include_str!("../../.opencode/agents/dreamer.md")),
        ("pixel", include_str!("../../.opencode/agents/pixel.md")),
        ("forge", include_str!("../../.opencode/agents/forge.md")),
        ("scout", include_str!("../../.opencode/agents/scout.md")),
        ("voice", include_str!("../../.opencode/agents/voice.md")),
        ("probe", include_str!("../../.opencode/agents/probe.md")),
        ("iris", include_str!("../../.opencode/agents/iris.md")),
        ("verity", include_str!("../../.opencode/agents/verity.md")),
    ];
    for (id, bundled) in agents {
        let path = directory.join(format!("{id}.md"));
        let existing = fs::read_to_string(&path).ok();
        if existing
            .as_deref()
            .map(|text| !text.contains("Generated by Agent Bots"))
            .unwrap_or(false)
        {
            continue;
        }
        let content = bundled.replace("C:\\\\Users\\\\Hp\\\\Obsidian\\\\DevVault", &vault);
        fs::write(&path, content)
            .map_err(|error| format!("Could not install {}: {error}", path.display()))?;
    }
    Ok(())
}

fn read_policy_file(path: &Path) -> PolicyFile {
    let display = path.display().to_string();
    match fs::read_to_string(path) {
        Ok(content) => PolicyFile {
            path: display,
            exists: true,
            hash: fnv1a(&content),
            bytes: content.len(),
            content,
            error: None,
        },
        Err(error) => PolicyFile {
            path: display,
            exists: false,
            content: String::new(),
            hash: String::new(),
            bytes: 0,
            error: Some(error.to_string()),
        },
    }
}

#[tauri::command]
fn read_policy(project_root: Option<String>) -> PolicyBundle {
    let global = read_policy_file(&global_policy_path());
    let project = project_root.map(|root| read_policy_file(&PathBuf::from(root).join("AGENTS.md")));
    PolicyBundle {
        global,
        project,
        loaded_at: now_ms(),
    }
}

